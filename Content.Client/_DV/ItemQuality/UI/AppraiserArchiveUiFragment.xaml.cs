    private static void AddSectionHeader(BoxContainer parent, string text)
    {
        var label = new RichTextLabel
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 4, 0, 0),
        };
        var msg = new FormattedMessage();
        msg.AddMarkupOrThrow($"[bold][color=#88aacc]{FormattedMessage.EscapeText(text)}[/color][/bold]");
        label.SetMessage(msg);
        parent.AddChild(label);
    }

    private static void AddMarkupLine(BoxContainer parent, string markup)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        var msg = new FormattedMessage();
        try
        {
            msg.AddMarkupOrThrow(markup);
        }
        catch (Exception)
        {
            // Fallback: render as plain text if markup is invalid.
            msg.AddText(markup);
        }
        label.SetMessage(msg);
        parent.AddChild(label);
    }

    // ═══ Decrypt challenge inline control ═══

    /// <summary>
    /// Multi-type decryption challenge for PDA archive entries.
    /// Supports three challenge modes:
    /// - SignalLock: Single marker bouncing, click when in green zone.
    /// - CounterSweep: Two markers moving opposite, click when both in zone.
    /// - DriftLock: Single marker bouncing, zone slowly drifts.
    /// Features visual noise, pulsing zones, and marker glow effects.
    /// </summary>
    private sealed class DecryptChallenge : Control
    {
        public event Action<bool>? OnAttempt;

        private ChallengeType _type;
        private bool _active;

        // Primary marker
        private float _marker1;
        private float _speed1;
        private int _dir1 = 1;

        // Secondary marker (CounterSweep only)
        private float _marker2;
        private float _speed2;
        private int _dir2 = -1;

        // Zone
        private float _zoneStart;
        private float _zoneEnd;
        private float _zoneSpeed;
        private int _zoneDir = 1;
        private float _zoneCenter;
        private float _zoneSize;

        // Visual effects
        private float _pulseTimer;
        private float _noiseTimer;
        private readonly float[] _noiseSeg = new float[24];
        private readonly Color[] _noiseCol = new Color[24];

        public DecryptChallenge()
        {
            MinSize = new System.Numerics.Vector2(0, 32);
            HorizontalExpand = true;
            MouseFilter = MouseFilterMode.Stop;
            RegenerateNoise();
        }

        private void RegenerateNoise()
        {
            for (var i = 0; i < _noiseSeg.Length; i++)
            {
                _noiseSeg[i] = (float) Rng.NextDouble();
                var b = 0.04f + (float) Rng.NextDouble() * 0.08f;
                _noiseCol[i] = Rng.Next(2) == 0
                    ? new Color(b, b * 1.5f, b * 0.3f)
                    : new Color(b * 0.3f, b, b * 1.5f);
            }
        }

        public void Configure(ChallengeType type, float zoneCenter, float zoneSize, float speed, int round)
        {
            _type = type;
            _zoneSize = Math.Max(zoneSize, 0.06f);
            _zoneCenter = Math.Clamp(zoneCenter, _zoneSize / 2 + 0.02f, 1f - _zoneSize / 2 - 0.02f);
            _zoneStart = _zoneCenter - _zoneSize / 2;
            _zoneEnd = _zoneCenter + _zoneSize / 2;

            _marker1 = 0;
            _dir1 = 1;
            _speed1 = speed;

            switch (type)
            {
                case ChallengeType.CounterSweep:
                    _marker2 = 1;
                    _dir2 = -1;
                    _speed2 = speed * (0.85f + round * 0.1f);
                    break;
                case ChallengeType.DriftLock:
                    _zoneSpeed = 0.06f + round * 0.03f;
                    _zoneDir = Rng.Next(2) == 0 ? 1 : -1;
                    break;
            }

            _active = true;
            _pulseTimer = 0;
            _noiseTimer = 0;
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            if (!_active)
                return;

            var dt = args.DeltaSeconds;
            _pulseTimer += dt * 3f;
            _noiseTimer += dt;

            if (_noiseTimer > 0.12f)
            {
                _noiseTimer = 0;
                RegenerateNoise();
            }

            // Move primary marker
            _marker1 += _speed1 * _dir1 * dt;
            if (_marker1 >= 1) { _marker1 = 1; _dir1 = -1; }
            else if (_marker1 <= 0) { _marker1 = 0; _dir1 = 1; }

            // Move secondary marker (CounterSweep)
            if (_type == ChallengeType.CounterSweep)
            {
                _marker2 += _speed2 * _dir2 * dt;
                if (_marker2 >= 1) { _marker2 = 1; _dir2 = -1; }
                else if (_marker2 <= 0) { _marker2 = 0; _dir2 = 1; }
            }

            // Drift zone (DriftLock)
            if (_type == ChallengeType.DriftLock)
            {
                _zoneCenter += _zoneSpeed * _zoneDir * dt;
                if (_zoneCenter + _zoneSize / 2 >= 0.98f)
                {
                    _zoneCenter = 0.98f - _zoneSize / 2;
                    _zoneDir = -1;
                }
                else if (_zoneCenter - _zoneSize / 2 <= 0.02f)
                {
                    _zoneCenter = 0.02f + _zoneSize / 2;
                    _zoneDir = 1;
                }

                _zoneStart = _zoneCenter - _zoneSize / 2;
                _zoneEnd = _zoneCenter + _zoneSize / 2;
            }
        }

        protected override void KeyBindDown(GUIBoundKeyEventArgs args)
        {
            base.KeyBindDown(args);
            if (!_active || args.Function != EngineKeyFunctions.UIClick)
                return;

            args.Handle();
            _active = false;

            bool hit;
            switch (_type)
            {
                case ChallengeType.CounterSweep:
                    hit = _marker1 >= _zoneStart && _marker1 <= _zoneEnd
                       && _marker2 >= _zoneStart && _marker2 <= _zoneEnd;
                    break;
                default:
                    hit = _marker1 >= _zoneStart && _marker1 <= _zoneEnd;
                    break;
            }

            OnAttempt?.Invoke(hit);
        }

        protected override void Draw(DrawingHandleScreen handle)
        {
            base.Draw(handle);

            var w = (float) PixelWidth;
            var h = (float) PixelHeight;

            // Dark terminal background
            handle.DrawRect(new UIBox2(0, 0, w, h), new Color(0.04f, 0.06f, 0.1f));

            // Background noise segments
            var segW = w / _noiseSeg.Length;
            for (var i = 0; i < _noiseSeg.Length; i++)
            {
                var sx = i * segW;
                var sh = _noiseSeg[i] * h * 0.3f;
                var sy = (h - sh) / 2;
                handle.DrawRect(new UIBox2(sx, sy, sx + segW - 1, sy + sh), _noiseCol[i]);
            }

            // Zone with pulse glow
            var pulse = 0.5f + 0.15f * MathF.Sin(_pulseTimer);
            var zx1 = _zoneStart * w;
            var zx2 = _zoneEnd * w;
            handle.DrawRect(new UIBox2(zx1, 1, zx2, h - 1),
                new Color(0.05f, pulse * 0.4f, 0.15f, 0.7f));

            // Zone edge highlights
            var edgeW = 2f * UIScale;
            handle.DrawRect(new UIBox2(zx1, 1, zx1 + edgeW, h - 1),
                new Color(0.1f, 0.7f, 0.3f, 0.8f));
            handle.DrawRect(new UIBox2(zx2 - edgeW, 1, zx2, h - 1),
                new Color(0.1f, 0.7f, 0.3f, 0.8f));

            // For DriftLock, show zone center indicator
            if (_type == ChallengeType.DriftLock && _active)
            {
                var cx = _zoneCenter * w;
                handle.DrawRect(new UIBox2(cx - 1, 0, cx + 1, h),
                    new Color(0f, 1f, 0.5f, 0.15f));
            }

            // Primary marker (cyan glow + white line)
            DrawMarker(handle, _marker1, w, h,
                new Color(0.2f, 0.5f, 1f, 0.12f),
                new Color(0.7f, 0.9f, 1f));

            // Secondary marker for CounterSweep (orange glow + orange line)
            if (_type == ChallengeType.CounterSweep)
            {
                DrawMarker(handle, _marker2, w, h,
                    new Color(1f, 0.4f, 0.1f, 0.12f),
                    new Color(1f, 0.7f, 0.3f));
            }

            // Border
            handle.DrawRect(new UIBox2(0, 0, w, 1), new Color(0.15f, 0.2f, 0.3f));
            handle.DrawRect(new UIBox2(0, h - 1, w, h), new Color(0.15f, 0.2f, 0.3f));
            handle.DrawRect(new UIBox2(0, 0, 1, h), new Color(0.15f, 0.2f, 0.3f));
            handle.DrawRect(new UIBox2(w - 1, 0, w, h), new Color(0.15f, 0.2f, 0.3f));
        }

        private void DrawMarker(DrawingHandleScreen handle, float pos, float w, float h,
            Color glowColor, Color lineColor)
        {
            var mx = pos * w;
            var mw = 2f * UIScale;

            // Glow
            handle.DrawRect(new UIBox2(mx - mw * 4, 2, mx + mw * 4, h - 2), glowColor);
            // Line
            handle.DrawRect(new UIBox2(mx - mw, 1, mx + mw, h - 1), lineColor);
        }
    }
